import assert from 'node:assert/strict';
import { calculate, toKop, lineTotal } from '../src/core/estimate.ts';
const estimate = (lines, extra={}) => ({ lines, discountPercent:0,markupPercent:0,taxPercent:0,...extra });
const line = (category,quantity,priceKop) => ({id:category,category,quantity,priceKop,unit:'pcs',name:category});
assert.equal(toKop(1.23),123);
assert.equal(toKop(0.1+0.2),30);
assert.throws(()=>toKop(-1));
assert.equal(lineTotal(line('work',1.5,199)),299);
assert.throws(()=>lineTotal(line('work',-1,100)));
const a=calculate(estimate([line('work',2,12345),line('material',1,500),line('transport',1,1000),line('extra',1,200)],{discountPercent:10,markupPercent:5,taxPercent:20}));
assert.equal(a.subtotal,26390);
assert.deepEqual(a.groups,{work:24690,material:500,transport:1000,extra:200});
assert.equal(a.discount,2639);
assert.equal(a.markup,1188);
assert.equal(a.tax,4988);
assert.equal(a.total,29927);
assert.throws(()=>calculate(estimate([],{taxPercent:101})));
const source={...line('work',1,1000)};
const snapshot={...source};source.priceKop=2000;
assert.equal(lineTotal(snapshot),1000,'Existing estimate price remains independent of catalog changes');
console.log('PASS: 11 offline core assertions');
